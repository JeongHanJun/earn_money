#!/usr/bin/env node
// jeong760/lotto-data raw JSON → migrations/0002_bootstrap_data.sql 생성
//
// 실행: node scripts/bootstrap-jeong760.mjs
// 적용: npx wrangler d1 execute lotto-db --remote --file migrations/0002_bootstrap_data.sql
//
// 실측 스키마 (2026-09-20):
//   { updatedAt, latestRound, data: [
//     { drawNo, date, numbers:[6], bonusNo, prizes:[{rank,winners,prizePerWinner}], totalSales }
//   ]}

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC =
  "https://raw.githubusercontent.com/jeong760/lotto-data/main/data/lotto-history.json";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, "..", "seeds", "0002_bootstrap_data.sql");

function esc(v) {
  if (v == null) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function normalize(r, now) {
  if (!r || !Array.isArray(r.numbers) || r.numbers.length !== 6) return null;
  const sorted = [...r.numbers].sort((a, b) => a - b);
  const prize1 = r.prizes?.find?.((p) => p.rank === 1);
  return {
    drwNo: r.drawNo,
    drwDate: r.date,
    n: sorted,
    bonus: r.bonusNo,
    totalSales: r.totalSales ?? null,
    firstAmt: prize1?.prizePerWinner ?? null,
    firstCnt: prize1?.winners ?? null,
    prizes: (r.prizes ?? []).filter((p) => p.rank >= 1 && p.rank <= 5),
    now,
  };
}

function drawInsert(row) {
  return (
    `INSERT OR REPLACE INTO draws (drw_no, drw_date, n1, n2, n3, n4, n5, n6, bonus, total_sales, first_amt, first_cnt, first_method_auto, first_method_manual, first_method_semi, updated_at) VALUES (` +
    [
      esc(row.drwNo),
      esc(row.drwDate),
      esc(row.n[0]),
      esc(row.n[1]),
      esc(row.n[2]),
      esc(row.n[3]),
      esc(row.n[4]),
      esc(row.n[5]),
      esc(row.bonus),
      esc(row.totalSales),
      esc(row.firstAmt),
      esc(row.firstCnt),
      "NULL",
      "NULL",
      "NULL",
    ].join(", ") +
    `, ${row.now});`
  );
}

function prizeInsert(drwNo, p) {
  return `INSERT OR REPLACE INTO prizes (drw_no, rank, winners, amount) VALUES (${esc(drwNo)}, ${esc(p.rank)}, ${esc(p.winners)}, ${esc(p.prizePerWinner ?? p.amount ?? 0)});`;
}

async function main() {
  console.log(`[bootstrap] fetch ${SRC}`);
  const res = await fetch(SRC, { headers: { "User-Agent": "lotto-bootstrap/0.1" } });
  if (!res.ok) throw new Error(`fetch ${SRC} → ${res.status}`);
  const doc = await res.json();
  const rows = Array.isArray(doc?.data) ? doc.data : Array.isArray(doc) ? doc : [];
  console.log(`[bootstrap] source updatedAt=${doc.updatedAt} latestRound=${doc.latestRound} rows=${rows.length}`);

  const now = Date.now();
  const normalized = rows.map((r) => normalize(r, now)).filter(Boolean);
  console.log(`[bootstrap] normalized=${normalized.length}`);
  if (normalized.length === 0) throw new Error("0 rows normalized");
  normalized.sort((a, b) => a.drwNo - b.drwNo);

  const sqlLines = [
    "-- Auto-generated by scripts/bootstrap-jeong760.mjs — do not edit.",
    `-- Source: ${SRC}`,
    `-- Source updatedAt: ${doc.updatedAt} · latestRound: ${doc.latestRound}`,
    `-- Generated: ${new Date(now).toISOString()}`,
    `-- Draws: ${normalized.length} (drw_no ${normalized[0].drwNo}~${normalized.at(-1).drwNo})`,
    "",
    "BEGIN TRANSACTION;",
    "",
  ];

  for (const row of normalized) {
    sqlLines.push(drawInsert(row));
    for (const p of row.prizes) sqlLines.push(prizeInsert(row.drwNo, p));
  }

  sqlLines.push("", "COMMIT;", "");
  const sql = sqlLines.join("\n");
  await fs.writeFile(OUT, sql, "utf8");
  console.log(
    `[bootstrap] wrote ${OUT} · ${sqlLines.length.toLocaleString()} statements · ${sql.length.toLocaleString()} bytes`,
  );
  console.log(
    `\nNext:\n  npx wrangler d1 execute lotto-db --remote --file seeds/0002_bootstrap_data.sql`,
  );
}

main().catch((e) => {
  console.error("[fatal]", e);
  process.exit(1);
});
